/**
 * Builds the map data used by Map.svelte: one svg path (and a centroid) per state.
 * v1 downloaded us-atlas from a cdn and projected it with d3 in the browser on every visit.
 * v2 does the same work once, here, and commits the result (src/lib/map/mapData.ts).
 *
 * usage: npm run map   (only needed if the projection or the source data changes)
 */

import { readFileSync, writeFileSync } from 'fs';
import { createRequire } from 'module';
import { geoAlbersUsa, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import { presimplify, quantile, simplify } from 'topojson-simplify';
import type { Feature, FeatureCollection, Geometry } from 'geojson';
import type { GeometryCollection, Topology } from 'topojson-specification';
import { statesGraph } from '../src/lib/engine/statesGraph';

type StateFeature = Feature<Geometry, { name: string }>;

const require = createRequire(import.meta.url);
const source = JSON.parse(
	readFileSync(require.resolve('us-atlas/states-10m.json'), 'utf8')
) as Topology<{ states: GeometryCollection<{ name: string }> }>;

// 1:10m detail is far more than a ~550px map needs. simplifying the topology (not each shape)
// keeps shared borders identical, so neighbors never show gaps. keep 12% of the points
const presimplified = presimplify(source);
const topology = simplify(presimplified, quantile(presimplified, 0.12)) as typeof source;

// same projection as v1 (Map.svelte): 960 x 600 viewBox
const WIDTH = 960;
const HEIGHT = 600;
const projection = geoAlbersUsa().scale(1250).translate([480, 300]);
const pathGenerator = geoPath(projection).digits(1); // 0.1px precision keeps the file small

const states = feature(topology, topology.objects.states) as unknown as FeatureCollection<
	Geometry,
	{ name: string }
>;

const mapStates = states.features
	.map((state: StateFeature) => {
		const path = pathGenerator(state);
		if (!path) return null; // territories outside the albers usa projection (e.g. puerto rico)

		const [x, y] = pathGenerator.centroid(state);
		return {
			name: state.properties.name,
			path,
			centroid: [Math.round(x * 10) / 10, Math.round(y * 10) / 10] as [number, number],
			playable: state.properties.name in statesGraph // alaska, hawaii and dc are drawn but not playable
		};
	})
	.filter((state) => state !== null)
	.sort((a, b) => a.name.localeCompare(b.name));

const missing = Object.keys(statesGraph).filter((name) => !mapStates.some((s) => s.name === name));
if (missing.length > 0) throw new Error(`map is missing graph states: ${missing.join(', ')}`);

const output = `// generated by \`npm run map\` (scripts/build-map.ts) from us-atlas states-10m. do not edit by hand

export interface MapState {
	name: string;
	path: string; // svg path in the ${WIDTH} x ${HEIGHT} viewBox
	centroid: [number, number];
	playable: boolean; // false for alaska, hawaii and dc (drawn, but not in the graph)
}

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

// prettier-ignore
export const mapStates: MapState[] = ${JSON.stringify(mapStates, null, '\t')};
`;

writeFileSync('src/lib/map/mapData.ts', output);
console.log(
	`✅ wrote ${mapStates.length} states to src/lib/map/mapData.ts (${(output.length / 1024).toFixed(0)} kb)`
);
